test("independent solver constants, residuals and duration", () => {
  const cases: [number, number[][], number, number, number][] = [
    [100, [[105, 365]], .05, 1, .9523809523809524],
    [100, [[105, 366]], .04986003754670353, 1.0027397260273974, .9551175301143796],
    [100, [[5, 1], [105, 366]], .10494510800400492, .9527533947967481, .8622631005786532],
    [100, [[2.5, 181], [102.5, 365]], .05063026595778512, .9877021791036884, .9401044412167875],
    [90, [[100, 730]], .05409255338945978, 2, 1.8973665961010275],
    [105, [[100, 365]], -.047619047619047616, 1, 1.05],
    [105, [[105, 365]], 0, 1, 1],
    [100.1, [[100, 5]], -.07036526152883343, 5 / 365, .01473549725509873],
    [102.93118208, [[103, 5]], .05000000261429889, 5 / 365, .013046314383694606],
    [102.93118208, [[106, 5]], 7.538863301534818, 5 / 365, .0016042685839137442],
  ];
  for (const [price, dates, yieldExpected, mac, mod] of cases) {
    const flows = dates.map(([amount, days]) => ({ amount, time: days / 365 }));
    const solved = solveBondYield(price, flows)!;
    close(solved?.value, yieldExpected);
    assert.ok(solved.iterations <= 200);
    assert.ok(Math.abs(solved.residual) <= Math.max(1e-8, 1e-10 * price));
    // Independent ordinary power PV; no production pricing helper as oracle.
    const pv = (y: number) => dates.reduce((sum, [a, d]) => sum + a / (1 + y) ** (d / 365), 0);
    close(pv(solved.value), price, 1e-8);
    const duration = datedBondDuration(price, flows, solved.value)!;
    close(duration.macaulay, mac, 1e-8); close(duration.modified, mod, 1e-8);
    const h = Math.min(1e-4, (1 + solved.value) / 4);
    const fd = (pv(solved.value - h) - pv(solved.value + h)) / (2 * h * price);
    close(fd * 100000 * .0001, mod * 10, .01);
  }
  close(datedBondDuration(100, [{ amount: 2.5, time: 181 / 365 }, { amount: 102.5, time: 1 }], .05063026595778512)!.modified * 10, 9.401044412167875);
});
test("extreme positive, negative, near-minus-one and technical failures", () => {
  close(solveBondYield(16, [{ amount: 105, time: 1 }])?.value, 5.5625);
  close(solveBondYield(1e-8, [{ amount: 100, time: 1 }])?.value, 9999999999, .1);
  close(solveBondYield(100, [{ amount: .001, time: 1 }])?.value, -.99999, 1e-10);
  const y = -.99999, h = Math.min(1e-9, (1 + y) / 4);
  const fd = ((.001 / (1 + y - h)) - (.001 / (1 + y + h))) / (2 * h * 100);
  close(fd, 100000, .01);
  for (const p of [0, -1, NaN, Infinity]) assert.equal(solveBondYield(p, [{ amount: 100, time: 1 }]), null);
  for (const cf of [[], [{ amount: -1, time: 1 }], [{ amount: 1, time: 0 }], [{ amount: Infinity, time: 1 }]]) assert.equal(solveBondYield(100, cf), null);
  assert.equal(solveBondYield(1, [{ amount: 100, time: 1e-9 }]), null);
  assert.equal(bondPresentValue([{ amount: 100, time: 1000 }], -.99), null);
  assert.equal(datedBondDuration(99, [{ amount: 105, time: 1 }], .05), null);
});

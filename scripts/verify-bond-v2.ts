function close(actual: number | null | undefined, expected: number, tolerance = 1e-9) {
  assert.ok(actual !== null && actual !== undefined && Number.isFinite(actual) && Math.abs(actual - expected) <= tolerance, `${actual} != ${expected} (tol ${tolerance})`);
}
